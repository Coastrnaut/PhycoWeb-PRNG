"""Generate the committed perturbation table (spec FR-003, FR-007a, FR-012).

Floating point is used here only, offline (Constitution Principle I); the committed integer
values are authoritative. Writes phycoweb/lut.py and data/lut/perturbation_lut.hex.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LUT_PY = ROOT / "phycoweb" / "lut.py"
LUT_HEX = ROOT / "data" / "lut" / "perturbation_lut.hex"

LUT_BITS = 8
AMPLITUDE = 1024
INC_A = 4
INC_B = 6
COS_OFFSET = 64


def table() -> list:
    size = 1 << LUT_BITS
    # int() truncates toward zero (FR-007a); mask to the 16-bit two's-complement pattern.
    return [int(math.sin(2 * math.pi * i / size) * AMPLITUDE) & 0xFFFF for i in range(size)]


def render_py(values: list) -> str:
    rows = []
    for start in range(0, len(values), 8):
        rows.append("    " + ", ".join(f"0x{v:04X}" for v in values[start:start + 8]) + ",")
    return "\n".join([
        "# GENERATED by scripts/gen_lut.py — do not edit.",
        f"# T[i] = trunc0(sin(2*pi*i/{len(values)}) * {AMPLITUDE}) & 0xFFFF (spec FR-007a).",
        "",
        f"LUT_BITS = {LUT_BITS}",
        f"INC_A = {INC_A}",
        f"INC_B = {INC_B}",
        f"COS_OFFSET = {COS_OFFSET}",
        "",
        "PERTURBATION_LUT = (",
        *rows,
        ")",
        "",
    ])


def render_hex(values: list) -> str:
    return "".join(f"{v:04X}\n" for v in values)


def main(argv: list) -> int:
    values = table()
    outputs = {LUT_PY: render_py(values), LUT_HEX: render_hex(values)}

    if argv == ["--check"]:
        stale = [p for p, text in outputs.items()
                 if not p.exists() or p.read_bytes() != text.encode("utf-8")]
        for path in stale:
            print(f"STALE: {path.relative_to(ROOT).as_posix()}")
        if not stale:
            print("OK: generated table files are up to date")
        return 1 if stale else 0
    if argv:
        print("usage: gen_lut.py [--check]", file=sys.stderr)
        return 2

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
